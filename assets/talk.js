/* Audio lessons: a teacher talks through the lesson (recorded with ElevenLabs, see talks/).
   HUB.talks[id] = { src, dur, voice, paras: [[text, start seconds], ...] } comes from talks/index.js,
   generated by tools/build_talks.py (starts are estimated, then snapped to pauses in the audio).
   The transcript paragraph being spoken is highlighted; click one to jump there.
   When a paragraph carries word timings ([text, start, [gaps in centiseconds]], from tools/align_talks.py),
   each word lights up as it is spoken, the same way the read-aloud narration does. */
(function () {
  var KEY = "ac297p-talk-pos";
  var SPEEDS = [0.85, 1, 1.15, 1.3, 1.5];
  var IC = {
    play: '<svg viewBox="0 0 24 24" width="22" height="22" aria-hidden="true"><path d="M8 5.5v13l11-6.5z" fill="currentColor"/></svg>',
    pause: '<svg viewBox="0 0 24 24" width="22" height="22" aria-hidden="true"><path d="M7 5h3.5v14H7zM13.5 5H17v14h-3.5z" fill="currentColor"/></svg>',
    back: '<svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M3 12a9 9 0 1 0 3-6.7L3 8"/><path d="M3 3v5h5"/></svg>',
    fwd: '<svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M21 12a9 9 0 1 1-3-6.7L21 8"/><path d="M21 3v5h-5"/></svg>',
    head: '<svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M4 15v-3a8 8 0 0 1 16 0v3"/><rect x="3" y="14" width="5" height="7" rx="1.5"/><rect x="16" y="14" width="5" height="7" rx="1.5"/></svg>'
  };
  var current = null;

  function load() { try { return JSON.parse(localStorage.getItem(KEY) || "{}"); } catch (e) { return {}; } }
  function store(id, t) { try { var s = load(); s[id] = Math.round(t); localStorage.setItem(KEY, JSON.stringify(s)); } catch (e) {} }
  function clock(s) { s = Math.max(0, Math.floor(s || 0)); return Math.floor(s / 60) + ":" + ("0" + s % 60).slice(-2); }

  function mount(el, id) {
    if (current) { current.audio.pause(); current = null; }
    var T = HUB.talks && HUB.talks[id];
    if (!el || !T) return;
    var starts = T.paras.map(function (p) { return p[1] / T.dur; });
    var mins = Math.round(T.dur / 60);

    el.innerHTML =
      '<div class="talk-row">' +
        '<button type="button" class="talk-play" aria-label="Play audio lesson">' + IC.play + '</button>' +
        '<div class="talk-main">' +
          '<div class="talk-title"><span class="talk-k">' + IC.head + 'Audio lesson</span><span class="talk-meta">' + mins + ' min · a teacher walks you through it</span></div>' +
          '<div class="talk-bar"><span class="talk-time num">0:00</span>' +
            '<input type="range" class="talk-seek" min="0" max="' + Math.round(T.dur * 10) + '" value="0" step="1" aria-label="Seek">' +
            '<span class="talk-time talk-dur num">' + clock(T.dur) + '</span></div>' +
        '</div>' +
      '</div>' +
      '<div class="talk-ctl">' +
        '<button type="button" class="talk-btn" data-skip="-15" aria-label="Back 15 seconds">' + IC.back + '<span>15</span></button>' +
        '<button type="button" class="talk-btn" data-skip="15" aria-label="Forward 15 seconds">' + IC.fwd + '<span>15</span></button>' +
        '<button type="button" class="talk-btn talk-speed" aria-label="Playback speed">1×</button>' +
        '<button type="button" class="talk-btn talk-tx-btn" aria-expanded="false">Transcript</button>' +
      '</div>' +
      '<div class="talk-tx" hidden>' + T.paras.map(function (p, i) {
        var body = p[2] ? p[0].trim().split(/\s+/).map(function (w) { return '<span class="tw">' + w + '</span>'; }).join(" ") : p[0];
        return '<p data-i="' + i + '" tabindex="0">' + body + '</p>';
      }).join("") + '</div>';

    var audio = new Audio(); audio.preload = "metadata"; audio.src = T.src;
    var play = el.querySelector(".talk-play"), seek = el.querySelector(".talk-seek"), now = el.querySelector(".talk-time");
    var tx = el.querySelector(".talk-tx"), txBtn = el.querySelector(".talk-tx-btn"), sp = el.querySelector(".talk-speed");
    var paras = tx.querySelectorAll("p"), on = -1, dragging = false, txTouched = false;
    // word timings: absolute start time per word span, in transcript order
    var wT = [], wEl = [], wOn = -1, raf = 0;
    T.paras.forEach(function (p, i) {
      if (!p[2]) return;
      var t = p[1], spans = paras[i].querySelectorAll(".tw");
      p[2].forEach(function (g, k) { t += g / 100; if (spans[k]) { wT.push(t); wEl.push(spans[k]); } });
    });
    function word(t) {
      if (!wT.length) return;
      var lo = 0, hi = wT.length - 1, k = -1;
      while (lo <= hi) { var m = (lo + hi) >> 1; if (wT[m] <= t + 0.03) { k = m; lo = m + 1; } else hi = m - 1; }
      if (k === wOn) return;
      if (wEl[wOn]) wEl[wOn].classList.remove("on");
      wOn = k;
      if (!wEl[wOn]) return;
      wEl[wOn].classList.add("on");
      if (!tx.hidden) {  // keep the spoken word in view inside long paragraphs
        var r = wEl[wOn].getBoundingClientRect(), b = tx.getBoundingClientRect();
        if (r.bottom > b.bottom - 8 || r.top < b.top) tx.scrollTo({ top: tx.scrollTop + r.top - b.top - 40, behavior: "smooth" });
      }
    }
    function tick() { word(audio.currentTime); raf = audio.paused ? 0 : requestAnimationFrame(tick); }
    var saved = load()[id] || 0, speed = 1;
    try { speed = +localStorage.getItem(KEY + "-speed") || 1; } catch (e) {}
    function dur() { return audio.duration || T.dur; }
    if (saved > 5 && saved < T.dur - 10) { audio.currentTime = saved; paint(saved); }
    sp.textContent = speed + "×"; audio.playbackRate = speed;

    function paint(t) {
      if (!dragging) seek.value = Math.round(t * 10);
      seek.style.setProperty("--p", (t / dur() * 100).toFixed(2) + "%");
      now.textContent = clock(t);
      var f = t / dur(), k = 0;
      for (var i = 0; i < starts.length; i++) if (starts[i] <= f) k = i;
      if (k !== on) {
        if (paras[on]) paras[on].classList.remove("on");
        on = k; paras[on].classList.add("on");
        if (!tx.hidden && !audio.paused) {
          var r = paras[on].getBoundingClientRect(), b = tx.getBoundingClientRect();
          if (r.top < b.top || r.bottom > b.bottom) tx.scrollTo({ top: paras[on].offsetTop - tx.offsetTop - 12, behavior: "smooth" });
        }
      }
    }
    function state() {
      var p = !audio.paused;
      play.innerHTML = p ? IC.pause : IC.play;
      play.setAttribute("aria-label", p ? "Pause audio lesson" : "Play audio lesson");
      el.classList.toggle("playing", p);
      if (p && !raf && wT.length) raf = requestAnimationFrame(tick);
      if (!p && wEl[wOn]) { wEl[wOn].classList.remove("on"); wOn = -1; }
    }
    play.addEventListener("click", function () {
      if (audio.paused) {
        if (HUB.voice && HUB.voice.stop) HUB.voice.stop();
        if (audio.ended || audio.currentTime >= dur() - 0.5) audio.currentTime = 0;
        audio.play();
        if (tx.hidden && !txTouched && wT.length) showTx(true);
      } else audio.pause();
    });
    audio.addEventListener("play", state);
    audio.addEventListener("pause", function () { state(); store(id, audio.currentTime); });
    audio.addEventListener("ended", function () { state(); store(id, 0); });
    audio.addEventListener("timeupdate", function () { paint(audio.currentTime); if (Math.floor(audio.currentTime) % 5 === 0) store(id, audio.currentTime); });
    seek.addEventListener("input", function () { dragging = true; paint(seek.value / 10); });
    seek.addEventListener("change", function () { audio.currentTime = seek.value / 10; dragging = false; });
    el.querySelectorAll("[data-skip]").forEach(function (b) {
      b.addEventListener("click", function () { audio.currentTime = Math.max(0, Math.min(dur(), audio.currentTime + +b.getAttribute("data-skip"))); paint(audio.currentTime); });
    });
    sp.addEventListener("click", function () {
      speed = SPEEDS[(SPEEDS.indexOf(speed) + 1) % SPEEDS.length] || 1;
      audio.playbackRate = speed; sp.textContent = speed + "×";
      try { localStorage.setItem(KEY + "-speed", speed); } catch (e) {}
    });
    function showTx(show) {
      tx.hidden = !show; txBtn.setAttribute("aria-expanded", String(show));
      txBtn.classList.toggle("on", show);
      if (show && paras[on]) tx.scrollTop = Math.max(0, paras[on].offsetTop - tx.offsetTop - 12);
    }
    txBtn.addEventListener("click", function () { txTouched = true; showTx(tx.hidden); });
    function jump(p) { audio.currentTime = starts[+p.getAttribute("data-i")] * dur(); paint(audio.currentTime); if (audio.paused) play.click(); }
    paras.forEach(function (p) {
      p.addEventListener("click", function () { jump(p); });
      p.addEventListener("keydown", function (e) { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); jump(p); } });
    });
    paint(audio.currentTime || 0);
    current = { audio: audio, id: id };
  }

  HUB.talk = {
    mount: mount,
    has: function (id) { return !!(HUB.talks && HUB.talks[id]); },
    stop: function () { if (current) current.audio.pause(); },
    icon: IC.head
  };
})();
